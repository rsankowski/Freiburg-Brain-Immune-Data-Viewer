#!/usr/bin/env bash
# End-to-end smoke test on synthetic data: no real dataset required.
#
# Builds a sandbox under build/selftest with its own data/ and config/, runs
# every stage into it, and checks the outputs a reviewer would care about.
#
#   bash scripts/selftest.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SANDBOX="$ROOT/build/selftest"
RSCRIPT="${RSCRIPT_BIN:-/Library/Frameworks/R.framework/Resources/bin/Rscript}"
PY="${PYTHON_BIN:-$ROOT/.venv/bin/python}"
export PIPELINE_VENV_PYTHON="$PY"

rm -rf "$SANDBOX"
mkdir -p "$SANDBOX/data/Demo-et-al-2026" "$SANDBOX/config"
ln -s "$ROOT/scripts" "$SANDBOX/scripts"

echo "== generating synthetic input"
"$RSCRIPT" --vanilla "$ROOT/scripts/make_demo_data.R" \
  "$SANDBOX/data/Demo-et-al-2026/demo_dataset.rds" 600 400

cat > "$SANDBOX/config/pipeline.json" <<'JSON'
{
  "base_url": "http://localhost:8787/zarr",
  "s3_bucket": "example-bucket",
  "s3_region": "us-east-1",
  "s3_prefix": "",
  "site_origins": ["http://localhost:8787"],
  "hvg_target": 200,
  "max_categorical_cardinality": 100,
  "embedding_pattern": "^(umap|tsne|spatial)",
  "license": "CC-BY-4.0",
  "collection_title": "Pipeline self-test",
  "view_layout": "dual-umap",
  "datasets": {
    "demo_et_al_2026": {
      "title": "Synthetic demo dataset",
      "paper": "Demo et al. 2026",
      "description": "Synthetic data generated by scripts/make_demo_data.R.",
      "default_obs_set": "Subclass_label",
      "default_gene": "P2RY12",
      "skip": false,
      "obs_drop": [],
      "obs_keep_extra": [],
      "obs_numeric_coerce": ["Age"]
    }
  }
}
JSON

cd "$SANDBOX"
for stage in 01_inventory.R 02_trim.R 03_to_h5ad.R; do
  echo "== $stage"; "$RSCRIPT" --vanilla "$ROOT/scripts/$stage" >/dev/null
done
for stage in 04_to_zarr.py 05_configs.py 06_validate.py 07_sync.py 08_site.py; do
  echo "== $stage"; "$PY" "$ROOT/scripts/$stage" >/dev/null
done

echo "== checking outputs"
"$PY" - <<'PYCHECK'
import json, sys
from pathlib import Path
ok = True
def check(cond, msg):
    global ok
    print(("  ok   " if cond else "  FAIL ") + msg)
    ok = ok and cond

key = "demo_et_al_2026"
store = Path(f"build/zarr/{key}.zarr")
check(store.is_dir(), "zarr store written")
for meta in (".zgroup", "X/.zarray", "obs/.zattrs", "var/.zattrs", "obsm/X_umap/.zarray"):
    check((store / meta).exists(), f"{meta} present")

rep = json.load(open(f"build/checks/{key}_validate.json"))
check(rep["passed"], "stage 6 validation passed")
check(rep["n_obs"] == 600, f"600 cells round-tripped (got {rep['n_obs']})")

trim = json.load(open(f"build/trimmed/{key}_report.json"))
check("Subclass_color" not in trim["obs_kept"], "colour column lifted out of obs")
check("Subclass_label" in (trim["colour_maps"] or {}), "palette captured for Subclass_label")
check("constant_col" not in trim["obs_kept"], "single-valued column dropped")
check("Age_original" in trim["obs_kept"], "non-numeric ages preserved verbatim")

cfg = json.load(open(f"configs/{key}.json"))
comps = sorted(v["component"] for v in cfg["layout"])
check(comps.count("scatterplot") == 2, "two scatterplot views in the config")
check(all(f["url"].startswith("http") for d in cfg["datasets"] for f in d["files"]),
      "config references absolute URLs")

for page in ("docs/index.html", "docs/demo-et-al-2026.html", "docs/viewer.html"):
    check(Path(page).exists(), f"{page} generated")
for script in ("release/sync.sh", "release/apply-bucket-settings.sh"):
    check(Path(script).exists(), f"{script} generated (not run)")

print("\nSELF-TEST " + ("PASSED" if ok else "FAILED"))
sys.exit(0 if ok else 1)
PYCHECK
