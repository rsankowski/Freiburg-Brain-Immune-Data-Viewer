#!/usr/bin/env python
"""Stage 7 — generate the S3 release layout. Nothing is uploaded.

Writes to release/:
    sync.sh                  aws s3 sync commands, one per dataset (--size-only)
    apply-bucket-settings.sh bucket policy + CORS application
    bucket-policy.json       public s3:GetObject
    cors.json                GET/HEAD from the site origins, Content-Length/Range exposed
    README.md                bucket-root dataset description (AWS Open Data)
    LICENSE                  bucket-root licence

Review the generated scripts, then run them yourself.

    python scripts/07_sync.py [--dataset KEY]
"""
